<?php

declare(strict_types=1);

namespace App\Domain\Settlement;

use InvalidArgumentException;
use JsonException;

/**
 * The expected score of a player in parts per million, by the difference of ratings
 * (rival minus player). The table is data (content/tables/elo-expected-ppm.json), so the
 * game code never computes a power at run time and every platform gets the same numbers.
 */
final readonly class EloTable
{
    public const MIN_DIFFERENCE = -800;

    public const MAX_DIFFERENCE = 800;

    /** @param list<int> $expectedPpm index = difference - MIN_DIFFERENCE */
    private function __construct(private array $expectedPpm)
    {
        $size = self::MAX_DIFFERENCE - self::MIN_DIFFERENCE + 1;

        if (count($expectedPpm) !== $size) {
            throw new InvalidArgumentException('The table needs '.$size.' entries, got '.count($expectedPpm).'.');
        }
    }

    public static function fromJson(string $json): self
    {
        try {
            $data = json_decode($json, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new InvalidArgumentException('The Elo table is not valid JSON: '.$exception->getMessage(), 0, $exception);
        }

        $values = $data['expected_ppm'] ?? null;

        if (! is_array($values) || array_filter($values, static fn (mixed $value): bool => ! is_int($value)) !== []) {
            throw new InvalidArgumentException('The Elo table needs a list of integers in expected_ppm.');
        }

        return new self(array_values($values));
    }

    public static function fromFile(string $path): self
    {
        $json = @file_get_contents($path);

        if ($json === false) {
            throw new InvalidArgumentException("Cannot read the Elo table at {$path}.");
        }

        return self::fromJson($json);
    }

    /** Expected score for a rival that is `$difference` rating points above the player. Clamped to the table. */
    public function expectedPpm(int $difference): int
    {
        $clamped = max(self::MIN_DIFFERENCE, min(self::MAX_DIFFERENCE, $difference));

        return $this->expectedPpm[$clamped - self::MIN_DIFFERENCE];
    }

    /**
     * Computes the table with floating point numbers. This runs only to create the data file
     * and to check that it is not stale; settlement and ratings read the file.
     *
     * @return list<int>
     */
    public static function compute(): array
    {
        $values = [];

        for ($difference = self::MIN_DIFFERENCE; $difference <= self::MAX_DIFFERENCE; $difference++) {
            $values[] = (int) round(1_000_000 / (1 + 10 ** ($difference / 400)));
        }

        return $values;
    }

    /** The JSON stored in content/tables/elo-expected-ppm.json. */
    public static function computedJson(): string
    {
        return json_encode([
            'description' => 'Expected score of a player in ppm (1 000 000 = a sure win) by rating difference (rival minus player), index = difference + 800. Generated by php artisan content:elo-table.',
            'min_difference' => self::MIN_DIFFERENCE,
            'max_difference' => self::MAX_DIFFERENCE,
            'expected_ppm' => self::compute(),
        ], JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR)."\n";
    }
}
